//! Seed corpus generator for the fuzz targets: writes each seed below to
//! `fuzz/corpus/<target>/<name>`, as raw bytes. `just fuzz-generate-seed`
//! runs it, as `cargo +nightly run --manifest-path fuzz/Cargo.toml --bin
//! generate_seeds` does.

/// `name = "hex";` rows as `(name, hex)` pairs: the name is the seed's file.
macro_rules! seeds {
    ($($name:ident = $hex:expr;)*) => {
        &[$((stringify!($name), $hex)),*]
    };
}

