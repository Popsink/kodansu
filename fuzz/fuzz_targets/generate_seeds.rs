fn unhex(text: &str) -> Vec<u8> {
    let pairs = text
        .as_bytes()
        .chunks(2)
        .map(|pair| std::str::from_utf8(pair).unwrap());
    pairs
        .map(|pair| u8::from_str_radix(pair, 16).unwrap())
        .collect()
}

fn main() {
    let corpora = [
        ("fuzz_request_decode", FUZZ_REQUEST_DECODE),
        ("fuzz_response_decode", FUZZ_RESPONSE_DECODE),
        ("fuzz_deflated_batch", FUZZ_DEFLATED_BATCH),
        ("fuzz_varint", FUZZ_VARINT),
    ];
    for (target, seeds) in corpora {
        let corpus = std::path::Path::new("fuzz/corpus").join(target);
        std::fs::create_dir_all(&corpus).unwrap();
        for (name, hex) in seeds {
            let (seed, bytes) = (corpus.join(name), unhex(hex));
            std::fs::write(&seed, &bytes).unwrap();
            println!("wrote {} ({} bytes)", seed.display(), bytes.len());
        }
    }

    println!();
    println!("Done! Seed corpus generated.");
}
