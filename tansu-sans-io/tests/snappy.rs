fn unhex(text: &str) -> Vec<u8> {
    let pairs = text
        .as_bytes()
        .chunks(2)
        .map(|pair| std::str::from_utf8(pair).unwrap());
    pairs
        .map(|pair| u8::from_str_radix(pair, 16).unwrap())
        .collect()
}

/// Asserts that `frame` is a produce to partition 0 of `xtdb_log` of one
/// batch, counted as one record, which inflates to one record of `length`.
fn assert_one_record_of(frame: &[u8], length: i32) -> tansu_sans_io::Result<()> {
    let request = ProduceRequest::try_from(Frame::request_from_bytes(frame)?.body)?;
    let produced = request.topic_data.unwrap_or_default();
    let [topic] = &produced[..] else {
        panic!("one topic in {produced:?}")
    };
    let partitions = topic.partition_data.as_deref().unwrap_or_default();
    let partition = partitions.first().expect("first partition");
    let addressed = (topic.name.as_str(), partition.index);
    assert_eq!(("xtdb_log", 0), addressed);

    let batches = &partition.records.as_ref().expect("frame").batches;
    let [compressed] = &batches[..] else {
        panic!("one batch in {batches:?}")
    };
    assert_eq!(1, compressed.record_count);

    let records = inflated::Batch::try_from(compressed)?.records;
    let [record] = &records[..] else {
        panic!("one record in {records:?}")
    };
    assert_eq!(length, record.length);
    Ok(())
}

#[test]
fn batch_of_100_records_snappy_compressed() -> tansu_sans_io::Result<()> {
    let _guard = common::init_tracing()?;
    assert_one_record_of(&unhex(BATCH_OF_100), 7123)
}

