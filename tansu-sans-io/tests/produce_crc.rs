//! **Does the CRC check accept real client traffic?** (#271)
//!
//! `ProduceService` now refuses a batch whose CRC does not cover its payload,
//! answering CORRUPT_MESSAGE. That makes `Batch::crc_matches()` load-bearing for
//! availability: if our digest disagreed with any real producer's, we would
//! reject that producer's data outright.
//!
//! The licence for shipping the rejection was a production rate (zero mismatches
//! over 12h). This is the standing version of the same evidence: every captured
//! `ProduceRequest` in `decode.rs` — real bytes from `console-producer` (Java)
//! and `aiokafka` (Python), API v0 through v10, two of them snappy-compressed —
//! must verify.
//!
//! Why this cannot be broken by compression, which is worth stating because it
//! is not obvious: `crc_matches()` digests `batch.record_data`, and on the decode
//! path that is a **verbatim slice of the received bytes**. Nothing is
//! recompressed, so a codec difference cannot move the digest. The only ways to
//! diverge are the digested byte *range*, the field *order*, and the CRC
//! *polynomial* — all codec-independent, all pinned here.
//!
//! `decode.rs` already compares each capture's decoded CRC against one we
//! recompute, so this property held before this file existed. It held
//! *incidentally*: those tests never call `crc_matches()`, so they would keep
//! passing if it were broken. This names the property.

