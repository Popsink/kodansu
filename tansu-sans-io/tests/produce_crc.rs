/// Every batch in every captured produce request verifies.
#[test]
fn every_captured_produce_request_verifies() -> Result<()> {
    let captures: [(&str, &[u8]); 9] = [
        ("produce_request_v0_000", PRODUCE_REQUEST_V0_000),
        ("produce_request_v3_000", PRODUCE_REQUEST_V3_000),
        ("produce_request_v7_000", PRODUCE_REQUEST_V7_000),
        ("produce_request_v9_000", PRODUCE_REQUEST_V9_000),
        ("produce_request_v9_001", PRODUCE_REQUEST_V9_001),
        ("produce_request_v10_000", PRODUCE_REQUEST_V10_000),
        ("produce_request_v10_001", PRODUCE_REQUEST_V10_001),
        ("produce_request_v10_002", PRODUCE_REQUEST_V10_002),
        ("produce_request_v10_003", PRODUCE_REQUEST_V10_003),
    ];

    let mut batches_checked = 0usize;

    for (name, bytes) in captures {
        let request = Frame::request_from_bytes(bytes)
            .and_then(|frame| ProduceRequest::try_from(frame.body))?;

        for topic in request.topic_data.into_iter().flatten() {
            for partition in topic.partition_data.into_iter().flatten() {
                for batch in partition
                    .records
                    .into_iter()
                    .flat_map(|frame| frame.batches)
                {
                    assert!(
                        batch.crc_matches()?,
                        "{name}: a real client's batch does not verify — the produce path \
                         would answer CORRUPT_MESSAGE and refuse this producer's data. \
                         crc={} computed={} attributes={} record_count={}",
                        batch.crc,
                        batch.computed_crc()?,
                        batch.attributes,
                        batch.record_count,
                    );

                    batches_checked += 1;
                }
            }
        }
    }

    // The precondition. Without it an empty walk — a decode that yielded no
    // batches, a field renamed, a capture list that silently emptied — passes
    // while checking nothing.
    assert!(
        batches_checked >= 9,
        "expected at least one batch per capture, walked {batches_checked}",
    );

    Ok(())
}
