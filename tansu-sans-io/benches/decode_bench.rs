/// Each frame under the name its benchmark reports.
const FRAMES: [(&str, &str); 3] = [
    ("api_versions_request_v3_000", API_VERSIONS_REQUEST_V3_000),
    ("produce_request_v10_001", PRODUCE_REQUEST_V10_001),
    ("produce_request_v11_001", PRODUCE_REQUEST_V11_001),
];

/// Keeps the optimiser from folding a value away.
use std::hint::black_box as hidden;

fn unhex(text: &str) -> Vec<u8> {
    let pairs = text
        .as_bytes()
        .chunks(2)
        .map(|pair| std::str::from_utf8(pair).unwrap());
    pairs
        .map(|pair| u8::from_str_radix(pair, 16).unwrap())
        .collect()
}

/// Times `tansu_sans_io::Frame::request_from_bytes` on each of [`FRAMES`], decoded from hex
/// before the clock starts.
fn requests(c: &mut Criterion) {
    for (name, hex) in FRAMES {
        let frame = unhex(hex);
        let decodes = |b: &mut criterion::Bencher<'_>| {
            b.iter(|| hidden(tansu_sans_io::Frame::request_from_bytes(hidden(&frame[..])).is_ok()));
        };
        _ = c.bench_function(name, decodes);
    }
}

criterion_group!(decoding, requests);
criterion_main!(decoding);
